"""Incident reports: one data collection step, two renderers (PDF with ReportLab, Excel with openpyxl).

Contents (both formats): title information (period, generated at, generated by), incidents per hazard / camera /
day, status counts with false-alarm rate and unreviewed count, top zones, monitoring pauses in the period (hours
per camera and the list), the incident list, and the note that detections are decision support that need human
review (SRS 4.2.3). The PDF adds bar charts.
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field
from xml.sax.saxutils import escape
from datetime import date, datetime, time, timedelta
from pathlib import Path
from typing import Any

from sqlalchemy import text
from sqlalchemy.orm import Session

from app.pauses import ALL_CAMERAS, effective_end, state_of, when
from shared.contract import TZ, IncidentStatus, PauseReason

DISCLAIMER = ("Detections are produced by an AI model and are decision support only. They can be wrong "
              "(missed or false detections), so every incident needs human review before any action is taken.")
FA_RATE_HELP = "False-alarm rate = false alarms / incidents reviewed as Confirmed violation or False alarm."
TOP_ZONES = 10
PAUSE_NOTE = ("No incidents are detected while monitoring is paused, so the incident counts in this report do not "
              "cover these times.")
PDF_MAX_ROWS = 1500  # the incident list in the PDF is capped; the Excel file always has every incident


# ---------------------------------------------------------------- data

@dataclass
class ReportData:
    period_start: date
    period_end: date
    generated_at: datetime
    generated_by: str
    total: int = 0
    by_hazard: list[tuple[str, str, int]] = field(default_factory=list)      # (hazard_id, name, count)
    by_camera: list[tuple[int, str, int]] = field(default_factory=list)      # (camera_id, name, count)
    by_day: list[tuple[date, int]] = field(default_factory=list)             # every day of the period
    status_counts: dict[str, int] = field(default_factory=dict)              # all four statuses
    top_zones: list[tuple[str, str, str, int]] = field(default_factory=list)  # (camera, zone, type, count)
    incidents: list[dict[str, Any]] = field(default_factory=list)
    pauses: list[dict[str, Any]] = field(default_factory=list)                # overlapping the period, oldest first
    paused_hours: list[tuple[str, float]] = field(default_factory=list)      # (camera, hours paused in the period)

    @property
    def unreviewed(self) -> int:
        return self.status_counts.get(IncidentStatus.NEW.value, 0)

    @property
    def decided(self) -> int:
        return (self.status_counts.get(IncidentStatus.CONFIRMED.value, 0)
                + self.status_counts.get(IncidentStatus.FALSE_ALARM.value, 0))

    @property
    def false_alarm_rate(self) -> float | None:
        return self.status_counts.get(IncidentStatus.FALSE_ALARM.value, 0) / self.decided if self.decided else None

    def period_text(self) -> str:
        return f"{self.period_start:%d %b %Y} to {self.period_end:%d %b %Y}"


def period_bounds(start: date, end: date) -> tuple[str, str]:
    """[start 00:00, day after end 00:00) as +05:00 ISO text, matching how start_time is stored."""
    lo = datetime.combine(start, time(), TZ).isoformat(timespec="seconds")
    hi = datetime.combine(end + timedelta(days=1), time(), TZ).isoformat(timespec="seconds")
    return lo, hi


def collect(db: Session, start: date, end: date, generated_by: str, now: datetime | None = None) -> ReportData:
    lo, hi = period_bounds(start, end)
    p = {"lo": lo, "hi": hi}
    where = "i.start_time >= :lo AND i.start_time < :hi"
    data = ReportData(start, end, (now or datetime.now(TZ)).astimezone(TZ), generated_by)

    def rows(q: str) -> list[Any]:
        return list(db.execute(text(q), p))

    data.by_hazard = [(r[0], r[1], r[2]) for r in rows(
        f"SELECT h.hazard_id, h.name, COUNT(i.incident_id) FROM hazards h "
        f"LEFT JOIN incidents i ON i.hazard_id = h.hazard_id AND {where} GROUP BY h.hazard_id ORDER BY h.hazard_id")]
    data.by_camera = [(r[0], r[1], r[2]) for r in rows(
        f"SELECT c.camera_id, c.name, COUNT(i.incident_id) FROM cameras c "
        f"LEFT JOIN incidents i ON i.camera_id = c.camera_id AND {where} GROUP BY c.camera_id ORDER BY c.camera_id")]
    per_day = {r[0]: r[1] for r in rows(
        f"SELECT substr(i.start_time, 1, 10), COUNT(*) FROM incidents i WHERE {where} GROUP BY 1")}
    data.by_day = [(start + timedelta(days=n), per_day.get((start + timedelta(days=n)).isoformat(), 0))
                   for n in range((end - start).days + 1)]
    counts = {r[0]: r[1] for r in rows(f"SELECT i.status, COUNT(*) FROM incidents i WHERE {where} GROUP BY 1")}
    data.status_counts = {s.value: counts.get(s.value, 0) for s in IncidentStatus}
    data.total = sum(data.status_counts.values())
    data.top_zones = [(r[0], r[1], r[2], r[3]) for r in rows(
        f"SELECT c.name, z.name, z.type, COUNT(*) AS n FROM incidents i JOIN zones z ON z.zone_id = i.zone_id "
        f"JOIN cameras c ON c.camera_id = z.camera_id WHERE {where} GROUP BY z.zone_id "
        f"ORDER BY n DESC, z.zone_id LIMIT {TOP_ZONES}")]
    data.incidents = [dict(r._mapping) for r in rows(
        f"SELECT i.incident_id, i.start_time, i.end_time, i.hazard_id, h.name AS hazard_name, "
        f"c.name AS camera_name, z.name AS zone_name, i.severity, i.status FROM incidents i "
        f"JOIN hazards h ON h.hazard_id = i.hazard_id JOIN cameras c ON c.camera_id = i.camera_id "
        f"JOIN zones z ON z.zone_id = i.zone_id WHERE {where} ORDER BY i.start_time, i.incident_id")]
    data.pauses, data.paused_hours = collect_pauses(db, lo, hi, data.generated_at)
    return data


def _union(spans: list[tuple[datetime, datetime]]) -> timedelta:
    total, cur_s, cur_e = timedelta(), None, None
    for s, e in sorted(spans):
        if cur_e is None or s > cur_e:
            if cur_e is not None:
                total += cur_e - cur_s
            cur_s, cur_e = s, e
        else:
            cur_e = max(cur_e, e)
    return total + (cur_e - cur_s if cur_e is not None else timedelta())


def collect_pauses(db: Session, lo_iso: str, hi_iso: str, now: datetime) -> tuple[list[dict], list[tuple[str, float]]]:
    """Pauses overlapping [lo, hi), and paused hours per camera inside the period. Only time that has passed counts
    (a pause still running counts up to now; planned and cancelled pauses not at all). An all-cameras pause counts
    for every camera; overlapping times are counted once."""
    lo, hi = when(lo_iso), when(hi_iso)
    cams = [(r[0], r[1]) for r in db.execute(text("SELECT camera_id, name FROM cameras ORDER BY camera_id"))]
    spans: dict[int, list[tuple[datetime, datetime]]] = {cid: [] for cid, _ in cams}
    listed = []
    for row in db.execute(text(
            "SELECT p.*, c.name AS camera_name, COALESCE(u.full_name, u.username) AS by_name "
            "FROM monitoring_pauses p LEFT JOIN cameras c ON c.camera_id = p.camera_id "
            "LEFT JOIN users u ON u.user_id = p.created_by ORDER BY p.starts_at, p.pause_id")).mappings():
        row = dict(row)
        start, end = when(row["starts_at"]), effective_end(row)
        if start is None or state_of(row, now) == "cancelled":
            continue
        s, e = max(start, lo), min(t for t in (end, now, hi) if t is not None)
        if e <= s:
            continue
        listed.append({"camera": ALL_CAMERAS if row["camera_id"] is None else row["camera_name"],
                       "reason": PauseReason(row["reason"]).label, "note": row["note"], "start": start,
                       "end": end, "running": end is None or end > now, "in_period": e - s, "by": row["by_name"]})
        for cid in (list(spans) if row["camera_id"] is None else [row["camera_id"]]):
            if cid in spans:
                spans[cid].append((s, e))
    return listed, [(name, round(_union(spans[cid]).total_seconds() / 3600, 2)) for cid, name in cams]


def duration_text(td: timedelta) -> str:
    minutes = round(td.total_seconds() / 60)
    h, m = divmod(minutes, 60)
    return f"{h} h {m:02d} min" if h else f"{m} min"


def pause_end_text(p: dict[str, Any]) -> str:
    if p["end"] is None:
        return "until resumed (still paused)"
    end = p["end"].astimezone(TZ).strftime("%Y-%m-%d %H:%M")
    return f"{end} (still paused)" if p["running"] else end


def _local(iso: str | None) -> str:
    return datetime.fromisoformat(iso).astimezone(TZ).strftime("%Y-%m-%d %H:%M") if iso else ""


def nice_step(top: int, ticks: int = 5) -> int:
    """Axis step of 1, 2 or 5 x 10^n so that about `ticks` steps cover `top`."""
    raw = max(top, 1) / ticks
    mag = 10 ** math.floor(math.log10(raw)) if raw >= 1 else 1
    return max(1, int(next(m * mag for m in (1, 2, 5, 10) if m * mag >= raw)))


def _rate(data: ReportData) -> str:
    r = data.false_alarm_rate
    return f"{r:.1%} ({data.status_counts['False alarm']} of {data.decided})" if r is not None else "n/a (none decided)"


# ---------------------------------------------------------------- PDF

def write_pdf(data: ReportData, path: Path) -> None:
    from reportlab.graphics.charts.barcharts import VerticalBarChart  # noqa: PLC0415
    from reportlab.graphics.shapes import Drawing, String  # noqa: PLC0415
    from reportlab.lib import colors  # noqa: PLC0415
    from reportlab.lib.pagesizes import A4  # noqa: PLC0415
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet  # noqa: PLC0415
    from reportlab.lib.units import cm  # noqa: PLC0415
    from reportlab.platypus import (KeepTogether, PageBreak, Paragraph, SimpleDocTemplate, Spacer,  # noqa: PLC0415
                                    Table, TableStyle)

    ss = getSampleStyleSheet()
    h1, h2, body = ss["Title"], ss["Heading2"], ss["BodyText"]
    small = ParagraphStyle("small", parent=body, fontSize=8, leading=10, textColor=colors.HexColor("#555555"))
    note = ParagraphStyle("note", parent=body, fontSize=10, leading=13, borderColor=colors.HexColor("#c0392b"),
                          borderWidth=1, borderPadding=8, backColor=colors.HexColor("#fdf2f0"))
    cell = ParagraphStyle("cell", parent=body, fontSize=9, leading=11)
    accent = colors.HexColor("#2c6e9b")
    width = A4[0] - 4 * cm

    def table(rows: list[list[Any]], widths: list[float] | None = None, repeat: bool = False) -> Table:
        # Body cells become Paragraphs so long camera/zone names wrap instead of running into the next column.
        rows = rows[:1] + [[Paragraph(escape(c), cell) if isinstance(c, str) else c for c in r] for r in rows[1:]]
        t = Table(rows, colWidths=widths, repeatRows=1 if repeat else 0, hAlign="LEFT")
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), accent), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("FONTSIZE", (0, 0), (-1, -1), 9),
            ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#bbbbbb")),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f3f6f9")]),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ]))
        return t

    def bar_chart(labels: list[str], values: list[int], height: float = 6 * cm) -> Drawing:
        d = Drawing(width, height)
        c = VerticalBarChart()
        c.x, c.y, c.width, c.height = 1.2 * cm, 1.4 * cm, width - 1.6 * cm, height - 2 * cm
        c.data = [values or [0]]
        c.categoryAxis.categoryNames = labels or [""]
        c.categoryAxis.labels.fontSize = 7
        if len(labels) > 8:
            c.categoryAxis.labels.angle = 45
            c.categoryAxis.labels.boxAnchor = "ne"
        top = max(values or [0])
        step = nice_step(top)
        c.valueAxis.valueMin, c.valueAxis.valueStep = 0, step
        c.valueAxis.valueMax = max(step * math.ceil(top / step), step)
        c.valueAxis.labels.fontSize = 7
        c.bars[0].fillColor = accent
        c.bars[0].strokeColor = None
        d.add(c)
        if top == 0:
            d.add(String(width / 2, height / 2, "No incidents in this period", textAnchor="middle", fontSize=9))
        return d

    def day_labels() -> list[str]:
        n = len(data.by_day)
        every = max(1, -(-n // 20))  # at most ~20 labels
        return [f"{d:%d/%m}" if i % every == 0 else "" for i, (d, _) in enumerate(data.by_day)]

    def footer(canvas, doc) -> None:
        canvas.saveState()
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(colors.HexColor("#777777"))
        canvas.drawString(2 * cm, 1.2 * cm, f"RADS incident report, {data.period_text()}  |  "
                                            "Detections are decision support and need human review.")
        canvas.drawRightString(A4[0] - 2 * cm, 1.2 * cm, f"Page {doc.page}")
        canvas.restoreState()

    s = data.status_counts
    story: list[Any] = [
        Spacer(1, 4 * cm),
        Paragraph("RADS", ParagraphStyle("brand", parent=h1, textColor=accent, fontSize=14)),
        Paragraph("Food-safety incident report", h1),
        Spacer(1, 1 * cm),
        table([["Period", data.period_text()],
               ["Generated", data.generated_at.strftime("%d %b %Y, %H:%M (PKT, UTC+05:00)")],
               ["Generated by", data.generated_by],
               ["Incidents in period", str(data.total)],
               ["Not yet reviewed", str(data.unreviewed)]], [5 * cm, width - 5 * cm]),
        Spacer(1, 1.5 * cm),
        Paragraph(f"<b>Important:</b> {DISCLAIMER}", note),
        PageBreak(),

        Paragraph("1. Summary", h2),
        table([["Status", "Incidents"]] + [[k, str(v)] for k, v in s.items()] + [["Total", str(data.total)]],
              [8 * cm, 3 * cm]),
        Spacer(1, 0.3 * cm),
        table([["Measure", "Value"],
               ["Unreviewed (status New)", str(data.unreviewed)],
               ["False-alarm rate", _rate(data)]], [8 * cm, 6 * cm]),
        Paragraph(FA_RATE_HELP, small),

        KeepTogether([Paragraph("2. Incidents per hazard", h2),
                      bar_chart([h for h, _, _ in data.by_hazard], [n for _, _, n in data.by_hazard]),
                      table([["Hazard", "Description", "Incidents"]] + [[h, nm, str(n)] for h, nm, n in data.by_hazard],
                            [2.5 * cm, 9 * cm, 3 * cm])]),
        KeepTogether([Paragraph("3. Incidents per camera", h2),
                      bar_chart([nm for _, nm, _ in data.by_camera], [n for _, _, n in data.by_camera]),
                      table([["Camera", "Incidents"]] + [[nm, str(n)] for _, nm, n in data.by_camera],
                            [11.5 * cm, 3 * cm])]),
        KeepTogether([Paragraph("4. Incidents per day", h2),
                      bar_chart(day_labels(), [n for _, n in data.by_day], 7 * cm)]),
        table([["Day", "Incidents"]] + [[f"{d:%a %d %b %Y}", str(n)] for d, n in data.by_day],
              [6 * cm, 3 * cm], repeat=True),

        Paragraph(f"5. Top zones (up to {TOP_ZONES})", h2),
        table([["Camera", "Zone", "Type", "Incidents"]] + [[c, z, t, str(n)] for c, z, t, n in data.top_zones]
              if data.top_zones else [["Camera", "Zone", "Type", "Incidents"], ["-", "No incidents", "", ""]],
              [4.5 * cm, 6 * cm, 2 * cm, 2.5 * cm]),

        KeepTogether([
            Paragraph("6. Monitoring paused", h2),
            Paragraph(PAUSE_NOTE, small),
            Spacer(1, 0.2 * cm),
            table([["Camera", "Paused in this period"]]
                  + [[nm, duration_text(timedelta(hours=h))] for nm, h in data.paused_hours], [11.5 * cm, 4 * cm])]),
        Spacer(1, 0.3 * cm),
        table([["Camera", "Reason", "From", "To", "In period", "Paused by"]]
              + [[p["camera"], p["reason"] + (f" ({p['note']})" if p["note"] else ""),
                  p["start"].astimezone(TZ).strftime("%Y-%m-%d %H:%M"), pause_end_text(p),
                  duration_text(p["in_period"]), p["by"] or ""] for p in data.pauses]
              if data.pauses else [["Camera", "Reason", "From", "To", "In period", "Paused by"],
                                   ["-", "Monitoring was not paused in this period", "", "", "", ""]],
              [2.4 * cm, 3.6 * cm, 2.6 * cm, 3.0 * cm, 2.0 * cm, 3.4 * cm], repeat=True),

        PageBreak(),
        Paragraph("7. Incident list", h2),
    ]
    rows = data.incidents[:PDF_MAX_ROWS]
    if len(data.incidents) > PDF_MAX_ROWS:
        story.append(Paragraph(f"Showing the first {PDF_MAX_ROWS} of {len(data.incidents)} incidents; "
                               "the Excel report lists all of them.", small))
    story.append(table(
        [["#", "Time", "Hazard", "Camera", "Zone", "Status"]]
        + [[str(i["incident_id"]), _local(i["start_time"]), f"{i['hazard_id']} {i['hazard_name']}",
            i["camera_name"], i["zone_name"], i["status"]] for i in rows]
        if rows else [["#", "Time", "Hazard", "Camera", "Zone", "Status"], ["", "No incidents", "", "", "", ""]],
        [1.0 * cm, 3.2 * cm, 5.0 * cm, 2.2 * cm, 2.4 * cm, 3.2 * cm], repeat=True))
    story += [Spacer(1, 0.6 * cm), Paragraph(f"<b>Note:</b> {DISCLAIMER}", note)]

    doc = SimpleDocTemplate(str(path), pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm, topMargin=2 * cm,
                            bottomMargin=2 * cm, title="RADS incident report", author=data.generated_by,
                            subject=data.period_text())
    doc.build(story, onFirstPage=footer, onLaterPages=footer)


# ---------------------------------------------------------------- Excel

def write_xlsx(data: ReportData, path: Path) -> None:
    from openpyxl import Workbook  # noqa: PLC0415
    from openpyxl.styles import Alignment, Font, PatternFill  # noqa: PLC0415

    wb = Workbook()
    ws = wb.active
    ws.title = "Summary"
    bold, head_font = Font(bold=True), Font(bold=True, color="FFFFFF")
    head_fill = PatternFill("solid", fgColor="2C6E9B")

    def header(row: int, values: list[str]) -> None:
        for col, v in enumerate(values, 1):
            cell = ws.cell(row, col, v)
            cell.font, cell.fill = head_font, head_fill

    r = 1
    ws.cell(r, 1, "RADS food-safety incident report").font = Font(bold=True, size=14)
    for label, value in (("Period", data.period_text()),
                         ("Generated", data.generated_at.strftime("%Y-%m-%d %H:%M (PKT, UTC+05:00)")),
                         ("Generated by", data.generated_by),
                         ("Incidents in period", data.total),
                         ("Not yet reviewed (New)", data.unreviewed),
                         ("False-alarm rate", data.false_alarm_rate if data.false_alarm_rate is not None else "n/a")):
        r += 1
        ws.cell(r, 1, label).font = bold
        cell = ws.cell(r, 2, value)
        if label == "False-alarm rate" and isinstance(value, float):
            cell.number_format = "0.0%"
    r += 1
    ws.cell(r, 1, FA_RATE_HELP).font = Font(italic=True, size=9)

    def section(title: str, columns: list[str], rows: list[list[Any]]) -> None:
        nonlocal r
        r += 2
        ws.cell(r, 1, title).font = Font(bold=True, size=12)
        r += 1
        header(r, columns)
        for row in rows:
            r += 1
            for col, v in enumerate(row, 1):
                ws.cell(r, col, v)

    section("Status counts", ["Status", "Incidents"],
            [[k, v] for k, v in data.status_counts.items()] + [["Total", data.total]])
    section("Incidents per hazard", ["Hazard", "Description", "Incidents"], [list(x) for x in data.by_hazard])
    section("Incidents per camera", ["Camera", "Incidents"], [[nm, n] for _, nm, n in data.by_camera])
    section("Incidents per day", ["Day", "Incidents"], [[d, n] for d, n in data.by_day])
    for row in ws.iter_rows(min_col=1, max_col=1):
        if isinstance(row[0].value, date):
            row[0].number_format = "yyyy-mm-dd"
    section(f"Top zones (up to {TOP_ZONES})", ["Camera", "Zone", "Type", "Incidents"],
            [list(z) for z in data.top_zones])
    section("Monitoring paused (hours in this period)", ["Camera", "Hours paused"],
            [[nm, h] for nm, h in data.paused_hours])
    r += 1
    ws.cell(r, 1, PAUSE_NOTE + " The pauses are listed on the sheet 'Monitoring paused'.").font = Font(
        italic=True, size=9)
    r += 2
    ws.cell(r, 1, "Note").font = bold
    ws.cell(r, 2, DISCLAIMER).alignment = Alignment(wrap_text=True, vertical="top")
    ws.row_dimensions[r].height = 45
    for col, w in zip("ABCD", (34, 60, 12, 12)):
        ws.column_dimensions[col].width = w

    li = wb.create_sheet("Incidents")
    cols = ["ID", "Start time", "End time", "Hazard ID", "Hazard", "Camera", "Zone", "Severity", "Status"]
    for col, v in enumerate(cols, 1):
        cell = li.cell(1, col, v)
        cell.font, cell.fill = head_font, head_fill
    for n, i in enumerate(data.incidents, 2):
        values = [i["incident_id"],
                  datetime.fromisoformat(i["start_time"]).astimezone(TZ).replace(tzinfo=None),
                  datetime.fromisoformat(i["end_time"]).astimezone(TZ).replace(tzinfo=None) if i["end_time"] else None,
                  i["hazard_id"], i["hazard_name"], i["camera_name"], i["zone_name"], i["severity"], i["status"]]
        for col, v in enumerate(values, 1):
            cell = li.cell(n, col, v)
            if isinstance(v, datetime):
                cell.number_format = "yyyy-mm-dd hh:mm:ss"
    li.freeze_panes = "A2"
    li.auto_filter.ref = f"A1:I{max(len(data.incidents) + 1, 1)}"
    for col, w in zip("ABCDEFGHI", (8, 20, 20, 10, 28, 14, 18, 10, 20)):
        li.column_dimensions[col].width = w
    ps = wb.create_sheet("Monitoring paused")
    ps.cell(1, 1, "Monitoring paused").font = Font(bold=True, size=12)
    ps.cell(2, 1, PAUSE_NOTE).font = Font(italic=True, size=9)
    pcols = ["Camera", "Reason", "Note", "From", "To", "Hours in period", "Paused by"]
    for col, v in enumerate(pcols, 1):
        cell = ps.cell(4, col, v)
        cell.font, cell.fill = head_font, head_fill
    if not data.pauses:
        ps.cell(5, 1, "Monitoring was not paused in this period")
    for n, p in enumerate(data.pauses, 5):
        values = [p["camera"], p["reason"], p["note"] or "", p["start"].astimezone(TZ).replace(tzinfo=None),
                  p["end"].astimezone(TZ).replace(tzinfo=None) if p["end"] and not p["running"]
                  else pause_end_text(p), round(p["in_period"].total_seconds() / 3600, 2), p["by"] or ""]
        for col, v in enumerate(values, 1):
            cell = ps.cell(n, col, v)
            if isinstance(v, datetime):
                cell.number_format = "yyyy-mm-dd hh:mm"
    for col, w in zip("ABCDEFG", (16, 30, 30, 18, 28, 16, 20)):
        ps.column_dimensions[col].width = w
    wb.properties.title = "RADS incident report"
    wb.properties.creator = data.generated_by
    wb.save(path)


def write_report(data: ReportData, fmt: str, path: Path) -> None:
    (write_pdf if fmt == "pdf" else write_xlsx)(data, path)
