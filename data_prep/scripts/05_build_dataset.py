#!/usr/bin/env python3
"""Phase 2 build: write dataset/ (images, labels, data.yaml, index.csv) from the cleaned table
(clean_lib.load_clean) and the APPROVED split (audit/split/split_per_frame.csv, approved 2026-11-20).
Also writes _work/expected_counts.json: every number computed from the in-memory table (route A),
to be compared later with what is re-read from disk (route B, 06_verify.py).

Usage: python 05_build_dataset.py <prepared_dir>
"""
import sys, json, shutil
from pathlib import Path
import numpy as np
import pandas as pd
import yaml
sys.path.insert(0, str(Path(__file__).parent))
from clean_lib import load_clean, CLASSES, CLASS_ID

OUT = Path(sys.argv[1]).resolve()
DS = OUT / "dataset"
if DS.exists():
    shutil.rmtree(DS)  # dataset/ is fully generated by this script; rebuild from scratch
for s in ("train", "val"):
    (DS / "images" / s).mkdir(parents=True); (DS / "labels" / s).mkdir(parents=True)

F, B, log, cd, dup, tiny = load_clean(OUT)
split = pd.read_csv(OUT / "audit" / "split" / "split_per_frame.csv", dtype={"clip": str})
assert set(split.frame_id) == set(F.frame_id) and split.frame_id.is_unique, "approved split does not match cleaned frames"
F = F.rename(columns={"split": "annotator_split"})  # annotator's own tag, not used
F = F.merge(split[["frame_id", "split"]], on="frame_id")
B = B.merge(F[["frame_id", "split"]], on="frame_id")
# the approved split is by clip: check no clip is on both sides
assert (F.groupby("clip").split.nunique() == 1).all()

# source locations (zip + path inside it, or folder)
zips = pd.read_csv(OUT / "audit" / "inventory_zips.csv")
zip_of = {Path(r.extracted_to).name: r.zip for r in zips.itertuples() if isinstance(r.extracted_to, str)}
exports = pd.read_csv(OUT / "_work" / "exports.csv")
root_of = dict(zip(exports.export, exports.path))


def source_ref(path, export):
    if not isinstance(path, str) or not path:
        return ""
    rel = str(Path(path).relative_to(root_of[export]))
    return f"{zip_of[export]}::{rel}" if export in zip_of else path


rows = []
B = B.sort_values(["frame_id", "box_idx"])
by_f = {f: g for f, g in B.groupby("frame_id")}
for r in F.sort_values("frame_id").itertuples():
    ext = Path(r.raw_path).suffix.lower()
    img_dst = DS / "images" / r.split / f"{r.frame_id}{ext}"
    lab_dst = DS / "labels" / r.split / f"{r.frame_id}.txt"
    shutil.copyfile(r.raw_path, img_dst)  # byte copy, no re-encoding
    g = by_f.get(r.frame_id)
    lines = [] if g is None else [f"{CLASS_ID[b.class_name]} {b.cx:.6f} {b.cy:.6f} {b.bw:.6f} {b.bh:.6f}" for b in g.itertuples()]
    lab_dst.write_text("\n".join(lines) + ("\n" if lines else ""))
    rows.append({"frame_id": r.frame_id, "split": r.split, "restaurant_id": r.restaurant_id,
                 "session_id": r.session_id, "clip": r.clip, "recording_date": r.recording_date,
                 "camera_view": r.camera_view, "camera": r.camera, "clip_file": r.clip_file,
                 "frame_index": int(r.frame_index), "annotator": r.annotator, "num_boxes": len(lines),
                 "image_path": str(img_dst.relative_to(DS)), "label_path": str(lab_dst.relative_to(DS)),
                 "source_export": r.export, "source_raw_image": source_ref(r.raw_path, r.export),
                 "source_annotated_image": source_ref(r.annotated_path, r.export),
                 "source_sha1": r.sha1, "width": int(r.real_width), "height": int(r.real_height)})
IDX = pd.DataFrame(rows)
IDX.to_csv(DS / "index.csv", index=False)

data_yaml = {"path": str(DS), "train": "images/train", "val": "images/val",
             "names": {i: c for i, c in enumerate(CLASSES)}}
with open(DS / "data.yaml", "w") as f:
    f.write(f"path: {DS}\ntrain: images/train\nval: images/val\n"
            "# test: added later, when the separately recorded test set is ready\nnames:\n")
    for i, c in enumerate(CLASSES):
        f.write(f"  {i}: {c}\n")
assert yaml.safe_load(open(DS / "data.yaml"))["names"] == data_yaml["names"]

# ---------------- route A: expected counts from the in-memory table
HZ_FROM_CLASS = {"H-01": ["head_uncovered"], "H-03": ["smoking"], "H-05": ["bin_open"], "H-06": ["no_apron"], "H-08": ["mask_off"]}
RULE_INPUTS = {"H-02": "hand_bare + rte_food in the same frame", "H-04": "phone in the frame",
               "H-07": "raw_meat + a hand (hand_bare or hand_gloved) in the same frame"}


def counts(Fs, Bs):
    d = {"frames": len(Fs), "boxes": len(Bs), "background_frames": int((Fs.num_boxes_clean == 0).sum()),
         "boxes_per_class": {c: int((Bs.class_name == c).sum()) for c in CLASSES},
         "frames_with_class": {c: int(Bs[Bs.class_name == c].frame_id.nunique()) for c in CLASSES},
         "frames_per_camera": Fs.camera.value_counts().sort_index().to_dict(),
         "frames_per_clip": Fs["clip"].value_counts().sort_index().to_dict(),
         "frames_per_recording_date": Fs.recording_date.value_counts().sort_index().to_dict(),
         "frames_per_annotator": Fs.annotator.value_counts().sort_index().to_dict(),
         "resolutions": (Fs.real_width.astype(int).astype(str) + "x" + Fs.real_height.astype(int).astype(str)).value_counts().to_dict()}
    # hazard frames from annotator tags (route A uses the tags; route B will use the label files)
    hm = Fs.hazards_marked.fillna("")
    d["hazard_frames_tagged"] = {h: int(hm.str.contains(h).sum()) for h in HZ_FROM_CLASS}
    sets = {c: set(Bs[Bs.class_name == c].frame_id) for c in CLASSES}
    d["rule_input_frames"] = {"H-02": len(sets["hand_bare"] & sets["rte_food"]), "H-04": len(sets["phone"]),
                              "H-07": len(sets["raw_meat"] & (sets["hand_bare"] | sets["hand_gloved"]))}
    # box size at 640
    sc = 640 / np.maximum(Bs.meta_width, Bs.meta_height)
    w, h = Bs.bw * Bs.meta_width * sc, Bs.bh * Bs.meta_height * sc
    sh = np.minimum(w, h)
    d["box_size_640"] = {c: {"median_w": round(float(w[Bs.class_name == c].median()), 1),
                             "median_h": round(float(h[Bs.class_name == c].median()), 1),
                             "p10_w": round(float(w[Bs.class_name == c].quantile(.1)), 1),
                             "p10_h": round(float(h[Bs.class_name == c].quantile(.1)), 1),
                             "pct_short_lt16": round(float(100 * (sh[Bs.class_name == c] < 16).mean()), 1),
                             "pct_short_lt8": round(float(100 * (sh[Bs.class_name == c] < 8).mean()), 1)}
                         for c in CLASSES if (Bs.class_name == c).any()}
    return d


exp = {"overall": counts(F, B)}
for s in ("train", "val"):
    exp[s] = counts(F[F.split == s], B[B.split == s])
exp["frame_ids"] = sorted(F.frame_id)
exp["clips"] = {s: sorted(F[F.split == s]["clip"].unique()) for s in ("train", "val")}
exp["cleaning_log"] = log.to_dict("records")
exp["content_duplicates_removed"] = cd.to_dict("records")
exp["exact_duplicate_boxes_removed"] = dup.to_dict("records")
exp["tiny_boxes_removed"] = tiny.to_dict("records")
json.dump(exp, open(OUT / "_work" / "expected_counts.json", "w"), indent=1, default=str)
F.to_csv(OUT / "_work" / "frames_final.csv", index=False)
B.to_csv(OUT / "_work" / "boxes_final.csv", index=False)
print("written:", {s: int((IDX.split == s).sum()) for s in ("train", "val")}, "boxes", len(B))
