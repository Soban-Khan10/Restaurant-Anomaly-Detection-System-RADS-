# ---------------------------------------------------------------- POST /api/reports

def test_manager_creates_pdf(ctx, data):
    r = ctx.client.post("/api/reports", json={**PERIOD, "format": "pdf"}, headers=ctx.headers("manager"))
    assert r.status_code == 201, r.text
    rep = r.json()
    assert rep["format"] == "pdf" and rep["period_start"] == "2026-12-01" and rep["period_end"] == "2026-12-03"
    assert rep["created_by"] == ctx.ids["manager"] and rep["created_by_name"] == "Manager"
    assert rep["available"] is True and rep["download_url"] == f"/api/reports/{rep['report_id']}/download"
    assert re.fullmatch(r"RADS_report_2026-12-01_to_2026-12-03_\d{8}-\d{6}_[0-9a-f]{4}\.pdf", rep["file_name"])

    files = list((ctx.db_path.parent / "reports").iterdir())
    assert [f.name for f in files] == [rep["file_name"]]  # no leftover temporary file
    content = files[0].read_bytes()
    assert content.startswith(b"%PDF") and pdf_pages(content) >= 3  # title page, summary/charts, incident list

    row = ctx.sql("SELECT * FROM reports")[0]
    assert row["file_path"] == rep["file_name"] and row["created_by"] == ctx.ids["manager"]
    audit = ctx.audit("report_create")
    assert len(audit) == 1 and audit[0]["target_id"] == rep["report_id"]
    assert audit[0]["details"] == {"period_start": "2026-12-01", "period_end": "2026-12-03", "format": "pdf",
                                   "incidents": 5, "file": rep["file_name"]}


def test_admin_creates_xlsx_with_its_sheets(ctx, data):
    r = ctx.client.post("/api/reports", json={**PERIOD, "format": "xlsx"}, headers=ctx.headers("admin"))
    assert r.status_code == 201, r.text
    wb = openpyxl.load_workbook(ctx.db_path.parent / "reports" / r.json()["file_name"])
    assert wb.sheetnames == ["Summary", "Incidents", "Monitoring paused"]

    summary = {row[0]: row[1] for row in wb["Summary"].iter_rows(values_only=True) if row[0] is not None}
    assert summary["Period"] == "01 Dec 2026 to 03 Dec 2026"
    assert summary["Generated by"] == "Admin (admin)"
    assert summary["Incidents in period"] == 5 and summary["Not yet reviewed (New)"] == 1
    assert summary["False-alarm rate"] == pytest.approx(1 / 3)
    assert summary["Note"].startswith("Detections are produced by an AI model and are decision support only")

    rows = list(wb["Incidents"].iter_rows(values_only=True))
    assert rows[0] == ("ID", "Start time", "End time", "Hazard ID", "Hazard", "Camera", "Zone", "Severity", "Status")
    assert [r[0] for r in rows[1:]] == [data[k] for k in ("first", "a", "b", "c", "last")]
    assert rows[3][3:] == ("H-05", "Bin left open", "Camera 1", "Waste bin", "Medium", "Confirmed violation")


