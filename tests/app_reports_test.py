def test_collect_counts(ctx, data):
    with ctx.Session() as db:
        d = reports.collect(db, date(2026, 12, 1), date(2026, 12, 3), "Admin (admin)")
    assert d.total == 5  # boundaries: 00:00:00 of the first day and 23:59:59 of the last day are included
    assert [i["incident_id"] for i in d.incidents] == [data[k] for k in ("first", "a", "b", "c", "last")]
    assert d.by_hazard == [("H-01", "Head cover missing", 2), ("H-04", "Phone in preparation area", 0),
                           ("H-05", "Bin left open", 1), ("H-06", "Apron missing", 0), ("H-08", "Mask missing", 2)]
    assert d.by_camera == [(1, "Camera 1", 2), (2, "Camera 2", 3)]
    assert d.by_day == [(date(2026, 12, 1), 3), (date(2026, 12, 2), 0), (date(2026, 12, 3), 2)]
    assert d.status_counts == {"New": 1, "Acknowledged": 1, "Confirmed violation": 2, "False alarm": 1}
    assert d.unreviewed == 1 and d.decided == 3
    assert d.false_alarm_rate == pytest.approx(1 / 3)
    assert d.top_zones == [("Camera 2", "Prep area 2", "prep", 3), ("Camera 1", "Prep area 1", "prep", 1),
                           ("Camera 1", "Waste bin", "waste", 1)]


